/// 통화별 "한 주 변동 생활비" 추천 금액 4개. 통화마다 화폐 단위 규모가 크게 달라(KRW 10만원 ≈
/// USD 75 ≈ JPY 1만 엔 ≈ VND 150만 동), 한 가지 기준을 모든 통화에 그대로 쓰면 터무니없는
/// 금액이 나오므로 통화 코드별로 현실적인 규모를 따로 정의한다.
List<double> weeklyBudgetPresetsFor(String currencyCode) =>
    switch (currencyCode) {
      'USD' || 'EUR' => const [50.0, 75.0, 100.0, 150.0],
      'JPY' => const [10000.0, 15000.0, 20000.0, 30000.0],
      'VND' => const [1000000.0, 1500000.0, 2000000.0, 3000000.0],
      'TWD' => const [1500.0, 2000.0, 3000.0, 4500.0],
      'CNY' => const [300.0, 500.0, 700.0, 1000.0],
      'BRL' => const [250.0, 400.0, 500.0, 750.0],
      _ => const [100000.0, 150000.0, 200000.0, 300000.0], // KRW 기본값
    };
